CREATE TABLE IF NOT EXISTS clinical_cases (
    case_id SERIAL PRIMARY KEY,
    cme_no VARCHAR(30) UNIQUE NOT NULL,
    mlef_no VARCHAR(30) UNIQUE,
    patient_id INT NOT NULL REFERENCES patients(patient_id),
    patient_type VARCHAR(15) NOT NULL CHECK (patient_type IN ('Inward','Outpatient')),
    bht_no VARCHAR(30),
    ward VARCHAR(50),
    hospital VARCHAR(100),
    admission_datetime TIMESTAMPTZ,
    police_station_id INT REFERENCES police_stations(station_id),
    police_officer_name VARCHAR(100),
    police_officer_reg_no VARCHAR(30),
    police_contact_no VARCHAR(20),
    produced_by VARCHAR(100),
    examining_doctor_id INT NOT NULL REFERENCES users(user_id),
    examined_date DATE NOT NULL,
    place_of_examination VARCHAR(255),
    category VARCHAR(50),
    reason_for_examination TEXT,
    hurt_description TEXT,
    sr_no VARCHAR(30),
    case_status VARCHAR(30) NOT NULL DEFAULT 'Open',
    completed_on TIMESTAMPTZ,
    ordering_court_id INT REFERENCES courts(court_id),
    trial_court_id INT REFERENCES courts(court_id),
    case_no VARCHAR(30),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by INT NOT NULL REFERENCES users(user_id)
);
