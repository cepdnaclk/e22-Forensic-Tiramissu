CREATE TABLE IF NOT EXISTS autopsy_cases (
    case_id SERIAL PRIMARY KEY,
    pm_no VARCHAR(30) UNIQUE NOT NULL,
    morgue_no VARCHAR(30),
    patient_id INT NOT NULL REFERENCES patients(patient_id),
    inquest_no VARCHAR(30),
    case_no VARCHAR(50),
    police_station_id INT REFERENCES police_stations(station_id),
    police_officer_name VARCHAR(100),
    police_contact_no VARCHAR(15),
    examining_doctor_id INT NOT NULL REFERENCES users(user_id),
    pm_date DATE,
    place_of_pm VARCHAR(255),
    date_of_death DATE,
    time_of_death TIME,
    date_of_admission DATE,
    time_of_admission TIME,
    date_of_mor_adm DATE,
    time_of_mor_adm TIME,
    bht_no VARCHAR(250),
    ward VARCHAR(50),
    phn_no VARCHAR(50),
    is_hospital_death BOOLEAN DEFAULT FALSE,
    done_by VARCHAR(100),
    tech_1 VARCHAR(100),
    tech_2 VARCHAR(100),
    mode VARCHAR(100),
    storage VARCHAR(100),
    dd_no VARCHAR(50),
    verdict VARCHAR(30) CHECK (verdict IN ('Accident','Suicide','Homicide','Natural','Open','Undetermined')),
    ordering_court_id INT REFERENCES courts(court_id),
    trial_court_id INT REFERENCES courts(court_id),
    trial_case_no VARCHAR(50),
    case_status VARCHAR(30) NOT NULL DEFAULT 'Open',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by INT NOT NULL REFERENCES users(user_id)
);
